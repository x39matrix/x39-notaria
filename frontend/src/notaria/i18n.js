const LangCtx = createContext(null);

export const LANGS = [
  { code: 'en', label: 'EN', flag: '🇬🇧' },
  { code: 'es', label: 'ES', flag: '🇪🇸' },
  { code: 'zh', label: '中文', flag: '🇨🇳' },
  { code: 'ja', label: '日本語', flag: '🇯🇵' },
  { code: 'ar', label: 'العربية', flag: '🌐' },
];

export function LangProvider({ children }) {
  const [lang, setLangState] = useState(() => {
    const saved = localStorage.getItem('nt_lang');
    return LANGS.some((l) => l.code === saved) ? saved : 'en';
  });
  const setLang = (code) => {
    if (!LANGS.some((l) => l.code === code)) return;
    localStorage.setItem('nt_lang', code);
    setLangState(code);
  };
  const t = (key) => STRINGS[lang][key] ?? STRINGS.es[key] ?? key;
  useEffect(() => {
    document.documentElement.dir = lang === 'ar' ? 'rtl' : 'ltr';
    document.documentElement.lang = lang;
    document.title = t('meta.title');
    const md = document.querySelector('meta[name="description"]');
    if (md) md.setAttribute('content', t('meta.desc'));
    const og = document.querySelector('meta[property="og:title"]');
    if (og) og.setAttribute('content', t('meta.title'));
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [lang]);
  return <LangCtx.Provider value={{ lang, setLang, t }}>{children}</LangCtx.Provider>;
}

export const useLang = () => useContext(LangCtx);
